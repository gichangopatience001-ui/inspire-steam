# Program to do loop for sin cos and tan
import math

for x in range (-180,180,30):
    print(math.cos(x))
    print(math.tan(x))
    print(math.sin(x))

for y in range (0,180,30):
    print(math.cos(y))
    print(math.tan(y))
    print(math.sin(y))
    